package srcinfo

import (
	"slices"
	"strings"
	"testing"
)

const split = `# Generated by makepkg
pkgbase = foo
	pkgdesc = A test
	pkgver = 1.2
	pkgrel = 3
	epoch = 1
	arch = x86_64
	makedepends = go
	checkdepends = bats
	depends = glibc
	source = foo-1.2.tar.gz::https://Example.org/foo/v1.2.tar.gz
	source = fix.patch
	source = git+https://github.com/foo/bar.git#tag=v1
	source_x86_64 = https://dl.example.net/foo-x86_64.bin
	sha256sums = aaa
	sha256sums = bbb
	sha256sums = SKIP
	sha256sums_x86_64 = ccc
	install = foo.install

pkgname = foo
	depends = libfoo>=2

pkgname = foo-docs
	depends =
	install = docs.install
`

func TestParse(t *testing.T) {
	s, err := Parse(strings.NewReader(split))
	if err != nil {
		t.Fatal(err)
	}
	if s.PkgBase != "foo" {
		t.Errorf("pkgbase = %q", s.PkgBase)
	}
	if got := s.Version(); got != "1:1.2-3" {
		t.Errorf("version = %q", got)
	}
	if got := s.Names(); !slices.Equal(got, []string{"foo", "foo-docs"}) {
		t.Errorf("names = %v", got)
	}
	run, build := s.Depends("x86_64")
	if !slices.Equal(run, []string{"libfoo>=2"}) {
		t.Errorf("runtime depends = %v", run)
	}
	if !slices.Equal(build, []string{"go", "bats"}) {
		t.Errorf("build depends = %v", build)
	}
	if got := s.Install(); !slices.Equal(got, []string{"foo.install", "docs.install"}) {
		t.Errorf("install = %v", got)
	}
}

func TestSources(t *testing.T) {
	s, err := Parse(strings.NewReader(split))
	if err != nil {
		t.Fatal(err)
	}
	srcs := s.Sources("x86_64")
	if len(srcs) != 4 {
		t.Fatalf("got %d sources", len(srcs))
	}
	tests := []struct {
		file, host, sum string
		remote, vcs     bool
	}{
		{"foo-1.2.tar.gz", "example.org", "aaa", true, false},
		{"fix.patch", "", "bbb", false, false},
		{"bar", "github.com", "SKIP", true, true},
		{"foo-x86_64.bin", "dl.example.net", "ccc", true, false},
	}
	for i, tt := range tests {
		src := srcs[i]
		if src.File() != tt.file || src.Host() != tt.host || src.Sums["sha256sums"] != tt.sum ||
			src.Remote() != tt.remote || src.VCS() != tt.vcs {
			t.Errorf("source %d = %+v (file %q host %q remote %v vcs %v)", i, src, src.File(), src.Host(), src.Remote(), src.VCS())
		}
	}
}

func TestParseErrors(t *testing.T) {
	for _, in := range []string{
		"",
		"pkgname = foo\n",
		"pkgbase = foo\n\tpkgver = 1\n",
		"pkgbase = foo\nnonsense\n",
		"pkgver = 1\npkgbase = foo\npkgname = foo\n",
	} {
		if _, err := Parse(strings.NewReader(in)); err == nil {
			t.Errorf("Parse(%q) = nil error", in)
		}
	}
}

func TestVCS(t *testing.T) {
	tests := map[string]bool{
		"git+https://x/y.git": true,
		"git://x/y":           true,
		"hg+https://x/y":      true,
		"svn+https://x/y":     true,
		"bzr+lp:x":            false,
		"fossil+https://x/y":  true,
		"https://x/y.git":     false,
		"local.patch":         false,
		"https://git.x/y":     false,
	}
	for u, want := range tests {
		if got := (Source{URL: u}).VCS(); got != want {
			t.Errorf("VCS(%q) = %v", u, got)
		}
	}
}

func TestHost(t *testing.T) {
	tests := map[string]string{
		"https://Example.org:8443/a":  "example.org",
		"git+ssh://git@github.com/a":  "github.com",
		"https://user:pw@host.net/x":  "host.net",
		"ftp://ftp.gnu.org/gnu/a.tgz": "ftp.gnu.org",
		"nothing":                     "",
	}
	for u, want := range tests {
		if got := Host(u); got != want {
			t.Errorf("Host(%q) = %q, want %q", u, got, want)
		}
	}
}
